const fallback="en";
export function normaliseLanguage(value){return value==="zh"?"zh":"en"}
export function getStoredLanguage(){
  try{return normaliseLanguage(localStorage.getItem("ew_lang")||fallback)}catch{return fallback}
}
export function setStoredLanguage(lang){
  try{localStorage.setItem("ew_lang",normaliseLanguage(lang))}catch{}
}
export function translate(lang,key,vars={}){
  const dict=I18N[normaliseLanguage(lang)]||I18N[fallback];
  const raw=dict[key]??I18N[fallback][key]??key;
  return String(raw).replace(/\{(\w+)\}/g,(m,k)=>Object.prototype.hasOwnProperty.call(vars,k)?String(vars[k]):m)
}
